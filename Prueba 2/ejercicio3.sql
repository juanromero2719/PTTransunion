SELECT h.ID_HOGAR,
       h.CODIGO,
       m.NOMBRE                AS MUNICIPIO,
       m.DEPARTAMENTO,
       COUNT(i.ID_INTEGRANTE)  AS CANTIDAD_INTEGRANTES
  FROM HOGAR h
  LEFT JOIN MUNICIPIO m  ON m.ID_MUNICIPIO = h.ID_MUNICIPIO
  LEFT JOIN INTEGRANTE i ON i.ID_HOGAR = h.ID_HOGAR
 GROUP BY h.ID_HOGAR, h.CODIGO, m.NOMBRE, m.DEPARTAMENTO
 ORDER BY CANTIDAD_INTEGRANTES DESC, h.ID_HOGAR;


SELECT m.NOMBRE,
       m.DEPARTAMENTO,
       COUNT(h.ID_HOGAR) AS CANTIDAD_HOGARES
  FROM MUNICIPIO m
  JOIN HOGAR h ON h.ID_MUNICIPIO = m.ID_MUNICIPIO
 WHERE h.FECHA_REGISTRO >= SYSDATE - 365
 GROUP BY m.ID_MUNICIPIO, m.NOMBRE, m.DEPARTAMENTO
 ORDER BY CANTIDAD_HOGARES DESC
 FETCH FIRST 1 ROWS WITH TIES;


SELECT h.ID_HOGAR,
       h.CODIGO,
       COUNT(i.ID_INTEGRANTE)                                AS TOTAL_INTEGRANTES,
       COUNT(CASE WHEN i.TIENE_SUBSIDIO = 'S' THEN 1 END)    AS CANTIDAD_CON_SUBSIDIO
  FROM HOGAR h
  JOIN INTEGRANTE i ON i.ID_HOGAR = h.ID_HOGAR
 GROUP BY h.ID_HOGAR, h.CODIGO
HAVING COUNT(i.ID_INTEGRANTE) > 3
   AND COUNT(CASE WHEN i.TIENE_SUBSIDIO = 'S' THEN 1 END) >= 1
 ORDER BY h.ID_HOGAR;


